interface LanguageContextType {
  currentLanguage: string;
  setLanguage: (langCode: string) => void;
  currentOption: LanguageOption;
  t: (key: string, fallback?: string) => string;
  translateCrop: (cropName: string) => string;
  translateCategory: (cat: string) => string;
  availableLanguages: LanguageOption[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguageState] = useState<string>(() => {
    return localStorage.getItem('agroconnect_lang') || 'en';
  });

  const setLanguage = (code: string) => {
    setCurrentLanguageState(code);
    localStorage.setItem('agroconnect_lang', code);
  };

  const currentOption =
    INDIAN_LANGUAGES.find((l) => l.code === currentLanguage) || INDIAN_LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    if (dict && dict[key]) {
      return dict[key];
    }
    // Fallback to English dictionary
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  };

  const translateCrop = (cropName: string): string => {
    if (!cropName) return '';
    if (currentLanguage === 'en') return cropName;
    // Check if in dictionary
    for (const [key, mapping] of Object.entries(CROP_TRANSLATIONS)) {
      if (cropName.toLowerCase().includes(key.toLowerCase())) {
        if (mapping[currentLanguage]) {
          return mapping[currentLanguage];
        }
      }
    }
    return cropName;
  };

  const translateCategory = (cat: string): string => {
    if (!cat) return '';
    if (currentLanguage === 'en') return cat;
    const mapping = CATEGORY_TRANSLATIONS[cat];
    if (mapping && mapping[currentLanguage]) {
      return mapping[currentLanguage];
    }
    return cat;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage,
        currentOption,
        t,
        translateCrop,
        translateCategory,
        availableLanguages: INDIAN_LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
